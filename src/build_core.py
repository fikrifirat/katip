"""Assemble the browser-local Katip Redact (web-local/) from the server source.

Nothing is forked: recognizers.py, textutil.py and the word lists are copied
as-is from katip_redact/, and the overlap/merge rules are cut out of
analyzer.py with ast, so the browser always runs the same detection code as the
server. Re-run after changing the recognizers.

  python build.py <katip-redact dir> <node_modules dir> <out dir>
"""
import ast
import io
import shutil
import sys
import zipfile
from pathlib import Path

src, nm, out = (Path(a) for a in sys.argv[1:4])
pkg = src / "katip_redact"
here = Path(__file__).parent
out.mkdir(parents=True, exist_ok=True)

# 1. analyzer core (PRIORITY, FLAG_ONLY_DEFAULT, resolve_overlaps, _merge_adjacent)
tree = ast.parse((pkg / "analyzer.py").read_text())
want = {"PRIORITY", "FLAG_ONLY_DEFAULT", "resolve_overlaps", "_merge_adjacent"}
keep = [n for n in tree.body if (isinstance(n, ast.FunctionDef) and n.name in want) or
        (isinstance(n, ast.Assign) and any(getattr(t, "id", "") in want for t in n.targets))]
assert len(keep) == 4, [getattr(n, "name", "") for n in keep]
core = ("# generated by web-local/build.py from analyzer.py -- do not edit\n"
        "from __future__ import annotations\n" + "\n\n".join(ast.unparse(n) for n in keep) + "\n")

# 2. python bundle loaded into Pyodide
buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("katip_redact/__init__.py", "")
    for f in ("textutil.py", "recognizers.py"):
        z.write(pkg / f, f"katip_redact/{f}")
    z.writestr("katip_redact/_analyzer_core.py", core)
    for f in sorted((pkg / "data").glob("*.txt")):
        z.write(f, f"katip_redact/data/{f.name}")
    z.write(here / "py/presidio_shim.py", "presidio_analyzer/__init__.py")
    z.write(here / "py/local_detect.py", "local_detect.py")
    z.write(here / "py/local_formats.py", "local_formats.py")
    for f in sorted((here / "py/third_party/kvkk_pii").rglob("*.py")):  # vanilla baseline (MIT)
        z.write(f, str(f.relative_to(here / "py/third_party")))
(out / "katip_py.zip").write_bytes(buf.getvalue())

# 3. vendored runtimes: everything is served from the same origin, no CDN
V = out / "vendor"
copies = {
    "pyodide": ["pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"],
    "mupdf/dist": ["mupdf.js", "mupdf-wasm.js", "mupdf-wasm.wasm"],
    "tesseract.js/dist": ["tesseract.esm.min.js", "worker.min.js"],
    "tesseract.js-core": ["tesseract-core-simd-lstm.wasm.js", "tesseract-core-lstm.wasm.js", "tesseract-core-relaxedsimd-lstm.wasm.js"],
    "jszip/dist": ["jszip.min.js"],
}
for d, files in copies.items():
    for f in files:
        (V / d).mkdir(parents=True, exist_ok=True)
        shutil.copy2(nm / d / f, V / d / f)
(V / "tessdata").mkdir(exist_ok=True)
shutil.copy2(nm / "@tesseract.js-data/tur/4.0.0_best_int/tur.traineddata.gz", V / "tessdata/tur.traineddata.gz")
for f in ():
    if (here / f).exists() and here.resolve() != out.resolve():
        shutil.copy2(here / f, out / f)
print("built", out)
